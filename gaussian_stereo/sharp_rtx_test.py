"""Opt-in local experiment using the already benchmarked TensorRT RTX engine.

No automatic install or download; reuses ComfyUI CUDA context.
The engine is trusted local input, generated by the standalone benchmark.
"""
import hashlib
import logging
import math
import os
from pathlib import Path
import sys
import time

import numpy as np
import torch
import torch.nn.functional as F


log = logging.getLogger('sharp_vr_video')
REFERENCE = 'PyTorch (parity reference)'
RTX = 'TensorRT RTX (experimental)'
EXPECTED = {'image': (1, 3, 1536, 1536), 'disparity_factor': (1,),
            'mean_vectors': (1, 1179648, 3), 'singular_values': (1, 1179648, 3),
            'quaternions': (1, 1179648, 4), 'colors': (1, 1179648, 3),
            'opacities': (1, 1179648)}
ENGINE_NAME = 'sharp_fp16_rtx_1_7_1_116.engine'
_state = None
_seen = set()
_validated_engine = False


def folder(config):
    value = config.get('rtx_test_folder', '').strip()
    if not value:
        raise ValueError('Set rtx_test_folder to your standalone benchmark folder.')
    p = Path(value).expanduser().resolve()
    if not p.is_dir():
        raise ValueError(f'Standalone benchmark folder does not exist: {p}')
    return p


def release():
    global _state, _validated_engine
    _validated_engine = False
    if _state is not None:
        torch.cuda.synchronize(_state[0][1])
        _state = None


def load(config, device):
    global _state
    device = torch.device(device)
    if device.type != 'cuda' or os.name != 'nt':
        raise RuntimeError('TensorRT for RTX backend requires Windows NVIDIA CUDA.')
    root = folder(config)
    path = root / ENGINE_NAME
    if not path.is_file():
        raise FileNotFoundError(f'Run the standalone benchmark first: {path}')
    key = (str(path), device)
    if _state is not None and _state[0] == key:
        return _state
    release()
    site = root / 'isolated_python' / 'Lib' / 'site-packages'
    # Append only for the opt-in test. Existing ComfyUI packages take priority.
    # The runtime can lazily load its companion DLLs, so leave this path available.
    if site.is_dir() and str(site) not in sys.path:
        sys.path.append(str(site))
    try:
        import tensorrt_rtx as trt
    except ImportError as exc:
        raise RuntimeError('Cannot import TensorRT RTX from the standalone test folder. No packages installed.') from exc
    if trt.__version__ != '1.7.1.116':
        raise RuntimeError(f'Local engine requires TensorRT RTX 1.7.1.116, found {trt.__version__}')
    start = time.perf_counter()
    with torch.cuda.device(device):
        logger = trt.Logger(trt.Logger.WARNING)
        runtime = trt.Runtime(logger)
        engine = runtime.deserialize_cuda_engine(path.read_bytes())
        if engine is None:
            raise RuntimeError('Cannot deserialize the previously built TensorRT RTX engine.')
        context = engine.create_execution_context()
        if context is None:
            raise RuntimeError('Cannot create TensorRT RTX execution context.')
        names = [engine.get_tensor_name(i) for i in range(engine.num_io_tensors)]
        if set(names) != set(EXPECTED):
            raise RuntimeError(f'Unexpected TRT engine I/O: {names}')
        for name in names:
            mode = engine.get_tensor_mode(name)
            is_input = name in ('image', 'disparity_factor')
            if (mode == trt.TensorIOMode.INPUT) != is_input:
                raise RuntimeError(f'Unexpected tensor direction: {name}')
            if np.dtype(trt.nptype(engine.get_tensor_dtype(name))) != np.dtype(np.float32):
                raise RuntimeError(f'Unexpected dtype: {name}')
            if is_input and tuple(context.get_tensor_shape(name)) != EXPECTED[name]:
                if not context.set_input_shape(name, EXPECTED[name]):
                    raise RuntimeError(f'Cannot set input shape {name}')
        for name in names:
            if tuple(context.get_tensor_shape(name)) != EXPECTED[name]:
                raise RuntimeError(f'Unexpected tensor shape: {name}')
    _state = (key, trt, logger, runtime, engine, context, names)
    log.info('[SHARP VR Video] TensorRT RTX engine ready in %.2fs (%s)', time.perf_counter()-start, path)
    return _state


def predict(config, image_np, f_px, device, profile):
    global _validated_engine
    from .sharp.gaussians import Gaussians3D
    _, trt, logger, runtime, engine, context, names = load(config, device)
    width = image_np.shape[1]
    with torch.cuda.device(device):
        # Exactly the existing SHARP normalization and interpolation, in FP32
        # because the benchmarked ONNX graph exposes FP32 bindings.
        source = torch.from_numpy(image_np.copy()).float().to(device).permute(2, 0, 1) / 255.0
        image = F.interpolate(source[None], size=(1536, 1536), mode='bilinear', align_corners=True).contiguous()
        factor = torch.tensor([f_px / width], dtype=torch.float32, device=device)
        inputs = {'image': image, 'disparity_factor': factor}
        tensors = {}
        for name in names:
            host = engine.get_tensor_location(name) == trt.TensorLocation.HOST
            if name in inputs:
                tensor = inputs[name].cpu() if host else inputs[name]
            else:
                tensor = torch.empty(EXPECTED[name], dtype=torch.float32, device='cpu' if host else device)
            tensors[name] = tensor
            if not context.set_tensor_address(name, tensor.data_ptr()):
                raise RuntimeError(f'TRT binding failed: {name}')
        if profile is not None:
            profile.mark('input_model')
        stream = torch.cuda.current_stream(device)
        if not context.execute_async_v3(stream.cuda_stream):
            raise RuntimeError('TensorRT RTX inference failed; switch to PyTorch and restart ComfyUI.')
        # Keep all input/output allocations alive through inference. This also
        # surfaces execution failures at the frame that caused them.
        stream.synchronize()
        if profile is not None:
            profile.mark('encode')  # whole TRT forward, not just the encoder
            profile.mark('decode')  # zero, no separate decoder stage
        result = Gaussians3D(*(tensors[n].to(device) for n in Gaussians3D._fields))
        if not _validated_engine:
            samples = [v[0, ::32] for v in result]
            if not all(bool(torch.isfinite(v).all().item()) for v in samples):
                raise RuntimeError('TensorRT returned non-finite sampled Gaussian values; use PyTorch.')
            if not bool((result.singular_values[0, ::32] > 0).all().item()) or not bool((result.quaternions[0, ::32].norm(dim=-1) > 1e-8).all().item()):
                raise RuntimeError('TensorRT returned invalid sampled geometry; use PyTorch.')
            _validated_engine = True
    return result


def check_parity(config, image_np, f_px, g):
    from .sharp.gaussians import Gaussians3D, compose_covariance_matrices
    mode = config.get('inference_backend', 'PyTorch')
    if mode not in (REFERENCE, RTX):
        return
    root = folder(config)
    key = (str(root), mode)
    if key in _seen:
        return
    # First frame only. Compare identical indexed splats before unprojection.
    signature = hashlib.sha256(image_np.tobytes()).hexdigest()
    factor = float(f_px / image_np.shape[1])
    path = root / 'sharp_parity_reference.npz'
    values = {name: value[0, ::32].detach().float().cpu().numpy() for name, value in zip(Gaussians3D._fields, g)}
    if not all(np.isfinite(v).all() for v in values.values()):
        raise RuntimeError('Non-finite sampled Gaussian values: aborting experimental test.')
    if np.any(values['singular_values'] <= 0) or np.any(np.linalg.norm(values['quaternions'], axis=-1) < 1e-8):
        raise RuntimeError('Invalid sampled Gaussian scale or quaternion: aborting experimental test.')
    if mode == REFERENCE:
        np.savez_compressed(path, signature=signature, factor=factor, **values)
        log.info('[SHARP VR Video] Saved PyTorch parity reference (36,864 sampled splats): %s', path)
    else:
        if not path.is_file():
            log.warning('[SHARP VR Video] No PyTorch parity reference; run reference mode first.')
        else:
            with np.load(path, allow_pickle=False) as ref:
                if str(ref['signature'].item()) != signature or not math.isclose(float(ref['factor']), factor, rel_tol=1e-7):
                    log.info('[SHARP VR Video] Parity reference belongs to a different frame/focal length; skipping optional comparison.')
                    _seen.add(key)
                    return
                errors = {}
                for name, value in values.items():
                    if name == 'quaternions':
                        # q and -q encode the same rotation; covariance is more meaningful.
                        continue
                    base = ref[name].astype(np.float64)
                    errors[name] = np.linalg.norm(value.astype(np.float64)-base) / max(np.linalg.norm(base), 1e-12)
                def cov(q, s):
                    return compose_covariance_matrices(torch.from_numpy(q), torch.from_numpy(s)).numpy().astype(np.float64)
                a = cov(ref['quaternions'], ref['singular_values'])
                b = cov(values['quaternions'], values['singular_values'])
                errors['covariance'] = np.linalg.norm(b-a) / max(np.linalg.norm(a), 1e-12)
                log.info('[SHARP VR Video] PARITY relative L2 (sampled pre-unprojection): %s', ', '.join(f'{k}={v:.3%}' for k,v in errors.items()))
                # Gross mismatch guard, not a production quality certification.
                if errors['mean_vectors'] > .10 or errors['colors'] > .05:
                    raise RuntimeError('TRT parity gross mismatch (>10% centers or >5% colors). Do not use this output.')
    _seen.add(key)


def resolve_batch_backend(config, meta_batch, node_id, offset, timeline_valid):
    """Resolve Auto once per clip; never silently change backend mid-video."""
    import comfy.model_management as mm
    selected = dict(config)
    requested = selected.get('inference_backend', 'PyTorch')
    if requested == 'TensorRT for RTX (ONNX FP16)':
        requested = RTX
    if requested != 'Auto':
        selected['inference_backend'] = requested
        if requested == RTX and selected.get('dtype') != 'fp16':
            raise ValueError('TensorRT for RTX requires FP16 precision.')
        return selected
    if selected.get('dtype') != 'fp16' or not selected.get('rtx_test_folder', '').strip():
        selected['inference_backend'] = 'PyTorch'
        return selected
    key = str(node_id)
    state = getattr(meta_batch, '_sharp_vr_backend', None) if meta_batch is not None else None
    if meta_batch is not None and not timeline_valid:
        raise RuntimeError('Auto backend requires a verified Meta Batch timeline. Choose PyTorch or explicit TensorRT for this workflow.')
    if offset > 0:
        if state is None or key not in state:
            raise RuntimeError('Missing Auto backend selection for continuing video. Restart the queue.')
        selected['inference_backend'] = state[key]
        return selected
    chosen = 'PyTorch'
    if selected.get('dtype') == 'fp16' and selected.get('rtx_test_folder', '').strip():
        mm.throw_exception_if_processing_interrupted()
        try:
            load(selected, mm.get_torch_device())
            chosen = RTX
        except Exception as exc:
            mm.throw_exception_if_processing_interrupted()
            release()
            log.warning('[SHARP VR Video] RTX initialization unavailable; using PyTorch for this video: %s', exc)
    if meta_batch is not None:
        if state is None:
            state = {}
            meta_batch._sharp_vr_backend = state
        state[key] = chosen
    selected['inference_backend'] = chosen
    log.info('[SHARP VR Video] Auto selected %s for this video', 'TensorRT for RTX (ONNX FP16)' if chosen == RTX else chosen)
    return selected


def finish_batch_backend(meta_batch, node_id, release_now):
    if release_now:
        state = getattr(meta_batch, '_sharp_vr_backend', None)
        if state is not None:
            state.pop(str(node_id), None)
        release()
